#!/usr/bin/env node
/**
 * Generate out/.htaccess for static hosting on Apache/LiteSpeed (Hostinger).
 *
 * Why this exists: `output: 'export'` silently drops every redirect defined in
 * next.config.js ("redirects are not applied when exporting"). Hostinger is
 * LiteSpeed, which reads .htaccess, so the same redirect list can be re-emitted
 * as real 301s instead of being lost. This script is the bridge.
 *
 * next.config.js stays the single source of truth — never hand-edit the output.
 * Run after `next build`, which creates out/.
 *
 *   node scripts/gen-htaccess.mjs
 */
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "out");

if (!fs.existsSync(outDir)) {
  console.error("out/ does not exist — run `next build` first.");
  process.exit(1);
}

const cfg = require(path.join(root, "next.config.js"));
const config = typeof cfg === "function" ? await cfg() : await cfg;
const redirects = await (config.redirects?.() ?? []);

// Escape a literal path for use inside a RedirectMatch regex.
const rx = (p) =>
  p
    .replace(/[.+*?^${}()|[\]\\]/g, "\\$&")
    .replace(/^\//, "^/");

// Every destination must be a real page in the export, or we would be
// redirecting traffic from one 404 straight into another.
const destOk = (dest) => {
  const clean = dest.split("#")[0].split("?")[0];
  if (clean === "/") return true;
  const f = path.join(outDir, clean.replace(/^\//, "") + ".html");
  return fs.existsSync(f) || fs.existsSync(path.join(outDir, clean.replace(/^\//, ""), "index.html"));
};

const legacy = redirects.filter((r) => r.source !== "/reinvent");
const broken = legacy.filter((r) => !destOk(r.destination));
const line = (r) => `RedirectMatch 301 ${rx(r.source)}/?$ ${r.destination}`;

const generated = [
  "# ─────────────────────────────────────────────────────────────────────────────",
  "# GENERATED by scripts/gen-htaccess.mjs — DO NOT EDIT BY HAND.",
  "# Source of truth: next.config.js, redirects(). Re-run after changing them.",
  `# ${legacy.length} legacy redirects emitted as permanent (301).`,
  "# ─────────────────────────────────────────────────────────────────────────────",
  "",
  "# Serve /about from about.html rather than /about/ directory style",
  "Options -MultiViews",
  "DirectoryIndex index.html",
  "",
  "RewriteEngine On",
  "",
  "# ── 1. HTTPS + canonical host (apex, no www) ──────────────────────────────",
  "RewriteCond %{HTTPS} !=on",
  "RewriteRule ^(.*)$ https://wildranktechnologies.com/$1 [R=301,L]",
  "",
  "RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]",
  "RewriteRule ^(.*)$ https://%1/$1 [R=301,L]",
  "",
  "# ── 2. Legacy WordPress URLs → live pages ─────────────────────────────────",
  "# Each rule matches with or without a trailing slash, so a visitor reaches",
  "# the destination in ONE hop (the Next.js server took two).",
  ...legacy.map(line),
  "",
  "# ── 3. Trailing slash → no slash (matches the canonical tags) ─────────────",
  "RewriteCond %{REQUEST_FILENAME} !-d",
  "RewriteCond %{REQUEST_URI} !^/$",
  "RewriteRule ^(.+)/$ /$1 [R=308,L]",
  "",
  "# ── 4. Clean URLs: /about → /about.html ───────────────────────────────────",
  "RewriteCond %{REQUEST_FILENAME} !-f",
  "RewriteCond %{REQUEST_FILENAME} !-d",
  "RewriteCond %{REQUEST_FILENAME}\\.html -f",
  "RewriteRule ^(.+)$ $1.html [L]",
  "",
  "# ── 5. Errors ─────────────────────────────────────────────────────────────",
  "ErrorDocument 404 /404.html",
  "",
  "# ── 6. Caching ────────────────────────────────────────────────────────────",
  "# Next.js fingerprints everything under /_next/static, so it is safe to",
  "# cache immutably. HTML is NOT cached long so edits go live immediately.",
  "<IfModule mod_expires.c>",
  "  ExpiresActive On",
  "  ExpiresByType text/css                \"access plus 1 year\"",
  "  ExpiresByType application/javascript  \"access plus 1 year\"",
  "  ExpiresByType image/webp              \"access plus 6 months\"",
  "  ExpiresByType image/png               \"access plus 6 months\"",
  "  ExpiresByType image/svg+xml           \"access plus 6 months\"",
  "  ExpiresByType font/woff2              \"access plus 1 year\"",
  "  ExpiresByType text/html               \"access plus 0 seconds\"",
  "</IfModule>",
  "",
  "<IfModule mod_headers.c>",
  "  <FilesMatch \"\\.(js|css|woff2|png|jpg|jpeg|svg|webp|avif)$\">",
  "    Header set Cache-Control \"public, max-age=31536000, immutable\"",
  "  </FilesMatch>",
  "  Header set X-Content-Type-Options \"nosniff\"",
  "  Header set Referrer-Policy \"strict-origin-when-cross-origin\"",
  "</IfModule>",
  "",
].join("\n");

fs.writeFileSync(path.join(outDir, ".htaccess"), generated);

console.log(`  wrote out/.htaccess`);
console.log(`  ${legacy.length} redirects emitted as 301`);
console.log(`  ${broken.length} point at a page missing from this build:`);
broken.forEach((r) => console.log(`     ${r.source} -> ${r.destination}`));
if (broken.length === 0) console.log("     (none — every destination resolves to a real file)");
